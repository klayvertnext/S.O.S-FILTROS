create policy "sos_catalog_images_admin_insert"
on storage.objects for insert
to authenticated
with check (bucket_id = 'catalogo' and (select private.is_admin()));

drop policy if exists "sos_catalog_images_admin_update" on storage.objects;
create policy "sos_catalog_images_admin_update"
on storage.objects for update
to authenticated
